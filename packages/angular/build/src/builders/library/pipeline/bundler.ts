import assert from 'node:assert';
import path from 'node:path';
import type { OutputChunk, Plugin, RolldownOutput, RolldownPluginOption } from 'rolldown';
import { loadRolldown } from '../../../utils/load-rolldown';
import { toPosixPath } from '../../../utils/path';
import type { BundleResult, NormalizedEntryPoint, NormalizedLibraryOptions } from '../types';
import {
  FESM_OUTPUT_DIR,
  type MemoryOutputFile,
  TYPES_OUTPUT_DIR,
  createMemoryOutputFile,
} from './utils';

type RolldownPluginDtsModule = typeof import('rolldown-plugin-dts', {
  with: { 'resolution-mode': 'import' },
});

let rolldownPluginDtsPromise: Promise<RolldownPluginDtsModule> | undefined;

/**
 * Dynamically loads the `rolldown-plugin-dts` module after ensuring that
 * Rolldown's native binding has been initialized via `loadRolldown()`.
 *
 * @returns A promise resolving to the `rolldown-plugin-dts` module namespace.
 */
function loadRolldownPluginDts(): Promise<RolldownPluginDtsModule> {
  return (rolldownPluginDtsPromise ??= (async () => {
    // Ensure Rolldown's native binding is initialized via `loadRolldown()` before evaluating
    // `rolldown-plugin-dts`, which has top-level imports of `rolldown/experimental`.
    await loadRolldown();

    return import('rolldown-plugin-dts' as string) as Promise<RolldownPluginDtsModule>;
  })());
}

/**
 * Output of the entry point bundling process.
 */
export interface BundleEntryPointsOutput {
  /** In-memory files produced by bundling to be written to disk. */
  filesToEmit: MemoryOutputFile[];

  /** Map of entry point names to their bundle results. */
  bundleResults: Map<string, BundleResult>;

  /** Warning messages emitted during bundling. */
  warnings: string[];
}

/**
 * Input state for an individual entry point to be bundled.
 */
export interface BundleEntryPointInput {
  /** The normalized entry point to bundle. */
  entryPoint: NormalizedEntryPoint;

  /** Whether the entry point has changed ESM files requiring rebundling. */
  hasEsmChanges: boolean;

  /** Whether the entry point has changed TypeScript declaration files requiring rebundling. */
  hasDtsChanges: boolean;

  /** The previous bundle result from a prior build iteration, if available. */
  previousBundleResult?: BundleResult;
}

const ESM_EXTENSIONS = ['.js', '.mjs', '/index.js', '/index.mjs'] as const;
const DTS_EXTENSIONS = ['.d.ts', '.d.mts', '/index.d.ts', '/index.d.mts'] as const;

/**
 * Bundled module IDs, output files, and metadata for a single entry point bundle.
 */
interface EntryBundleOutput {
  /** Set of virtual POSIX module IDs included in the bundle. */
  moduleIds: Set<string>;

  /** Set of relative POSIX output paths generated for the bundle. */
  outputFiles: Set<string>;

  /** Whether the bundle imports 'tslib'. */
  hasTslibImport: boolean;
}

/**
 * Output of a multi-entry-point Rolldown bundling invocation.
 */
interface MultiBundleOutput {
  /** In-memory files generated by the bundle invocation. */
  filesToEmit: MemoryOutputFile[];

  /** Map of bundle entry names to their bundled module IDs, output files, and metadata. */
  bundles: Map<string, EntryBundleOutput>;

  /** Warning messages emitted during the bundle invocation. */
  warnings: string[];
}

/**
 * Expands the selected entry points to include any available entry points whose module IDs
 * transitively overlap with the selected set.
 */
function expandOverlappingEntryPoints(
  selectedEntryPoints: readonly NormalizedEntryPoint[],
  allEntryPoints: readonly NormalizedEntryPoint[],
  isAvailable: (ep: NormalizedEntryPoint) => boolean,
  getModuleIds: (ep: NormalizedEntryPoint) => ReadonlySet<string> | undefined,
): readonly NormalizedEntryPoint[] {
  assert(
    selectedEntryPoints.length <= allEntryPoints.length,
    'Selected entry points cannot exceed all entry points.',
  );
  if (selectedEntryPoints.length === allEntryPoints.length) {
    return selectedEntryPoints;
  }

  const selected = new Set(selectedEntryPoints);
  for (const ep of selected) {
    const moduleIds = getModuleIds(ep);
    if (!moduleIds?.size) {
      continue;
    }

    for (const candidate of allEntryPoints) {
      if (selected.has(candidate) || !isAvailable(candidate)) {
        continue;
      }

      const candidateIds = getModuleIds(candidate);
      if (candidateIds && !moduleIds.isDisjointFrom(candidateIds)) {
        selected.add(candidate);
      }
    }
  }

  return selected.size > selectedEntryPoints.length
    ? allEntryPoints.filter((ep) => selected.has(ep))
    : selectedEntryPoints;
}

/**
 * Checks whether any bundled entry point acquired a module ID that was not present in its
 * previous bundle result.
 */
function hasNewlyAddedModules(
  bundledEntryPoints: readonly NormalizedEntryPoint[],
  output: MultiBundleOutput,
  getPreviousModuleIds: (ep: NormalizedEntryPoint) => ReadonlySet<string> | undefined,
): boolean {
  for (const ep of bundledEntryPoints) {
    const bundle = output.bundles.get(ep.bundleName);
    assert(bundle, `Expected bundle output for entry point "${ep.bundleName}".`);

    const prevIds = getPreviousModuleIds(ep);
    if (!prevIds || !bundle.moduleIds.isSubsetOf(prevIds)) {
      return true;
    }
  }

  return false;
}

/**
 * Bundles dirty entry points for a single mode (ESM or DTS), automatically expanding the entry
 * point set before or after bundling when module IDs overlap across entry points.
 */
async function bundleModeWithSharedModules(
  dirtyEntryPoints: readonly NormalizedEntryPoint[],
  allEntryPoints: readonly NormalizedEntryPoint[],
  files: ReadonlyMap<string, string>,
  dtsMode: boolean,
  getPreviousModuleIds: (ep: NormalizedEntryPoint) => ReadonlySet<string> | undefined,
  bundleFn: (
    entryPoints: readonly NormalizedEntryPoint[],
    files: ReadonlyMap<string, string>,
    options: NormalizedLibraryOptions,
  ) => Promise<MultiBundleOutput>,
  options: NormalizedLibraryOptions,
): Promise<MultiBundleOutput> {
  if (dirtyEntryPoints.length === 0) {
    return { filesToEmit: [], bundles: new Map(), warnings: [] };
  }

  if (dirtyEntryPoints.length === allEntryPoints.length) {
    return bundleFn(dirtyEntryPoints, files, options);
  }

  const isAvailable = (ep: NormalizedEntryPoint): boolean =>
    files.has(resolveEntryInputPath(ep.entryFilePath, dtsMode));

  const initialEntryPoints = expandOverlappingEntryPoints(
    dirtyEntryPoints,
    allEntryPoints,
    isAvailable,
    getPreviousModuleIds,
  );
  const output = await bundleFn(initialEntryPoints, files, options);

  if (
    initialEntryPoints.length < allEntryPoints.length &&
    hasNewlyAddedModules(initialEntryPoints, output, getPreviousModuleIds)
  ) {
    const expandedEntryPoints = expandOverlappingEntryPoints(
      initialEntryPoints,
      allEntryPoints,
      isAvailable,
      (ep) => output.bundles.get(ep.bundleName)?.moduleIds ?? getPreviousModuleIds(ep),
    );

    if (expandedEntryPoints.length > initialEntryPoints.length) {
      return bundleFn(expandedEntryPoints, files, options);
    }
  }

  return output;
}

/**
 * Collects all normalized entry points from options and bundle input items.
 */
function getAllEntryPoints(
  items: readonly BundleEntryPointInput[],
  options: NormalizedLibraryOptions,
): NormalizedEntryPoint[] {
  const byName = new Map<string, NormalizedEntryPoint>();
  if (options.entryPoints) {
    for (const ep of options.entryPoints.values()) {
      byName.set(ep.name, ep);
    }
  }
  for (const item of items) {
    byName.set(item.entryPoint.name, item.entryPoint);
  }

  return Array.from(byName.values());
}

/**
 * Bundles the compiled in-memory JavaScript and declaration files for all dirty entry points
 * using at most 2 Rolldown instances per pass (1 for all .mjs bundles, 1 for all .d.ts bundles).
 *
 * @param items The collection of entry point inputs with change statuses.
 * @param esmFiles Map of virtual POSIX ESM output file paths to their content.
 * @param dtsFiles Map of virtual POSIX TypeScript declaration file paths to their content.
 * @param options The normalized library builder options with POSIX paths.
 * @param previousBundleResults Optional map of entry point names to their previous bundle results.
 * @returns A promise resolving to the bundled output files and bundle cache results.
 */
export async function bundleEntryPoints(
  items: readonly BundleEntryPointInput[],
  esmFiles: ReadonlyMap<string, string>,
  dtsFiles: ReadonlyMap<string, string>,
  options: NormalizedLibraryOptions,
  previousBundleResults?: ReadonlyMap<string, BundleResult>,
): Promise<BundleEntryPointsOutput> {
  const bundleResults = new Map<string, BundleResult>();
  if (items.length === 0) {
    return { filesToEmit: [], bundleResults, warnings: [] };
  }

  const allEntryPoints = getAllEntryPoints(items, options);
  const itemsByName = new Map(items.map((item) => [item.entryPoint.name, item]));
  const getPreviousResult = (name: string): BundleResult | undefined =>
    itemsByName.get(name)?.previousBundleResult ?? previousBundleResults?.get(name);

  const esmEntryPoints: NormalizedEntryPoint[] = [];
  const dtsEntryPoints: NormalizedEntryPoint[] = [];

  for (const item of items) {
    const { entryPoint } = item;
    const previousBundleResult = getPreviousResult(entryPoint.name);
    if (item.hasEsmChanges || !previousBundleResult) {
      esmEntryPoints.push(entryPoint);
    }
    if (item.hasDtsChanges || !previousBundleResult) {
      dtsEntryPoints.push(entryPoint);
    }
  }

  const [esmOutput, dtsOutput] = await Promise.all([
    bundleModeWithSharedModules(
      esmEntryPoints,
      allEntryPoints,
      esmFiles,
      false,
      (ep) => getPreviousResult(ep.name)?.esmModuleIds,
      bundleAllEsm,
      options,
    ),
    bundleModeWithSharedModules(
      dtsEntryPoints,
      allEntryPoints,
      dtsFiles,
      true,
      (ep) => getPreviousResult(ep.name)?.dtsModuleIds,
      bundleAllDts,
      options,
    ),
  ]);

  for (const entryPoint of allEntryPoints) {
    const item = itemsByName.get(entryPoint.name);
    const esmBundle = esmOutput.bundles.get(entryPoint.bundleName);
    const dtsBundle = dtsOutput.bundles.get(entryPoint.bundleName);
    if (!item && !esmBundle && !dtsBundle) {
      continue;
    }

    const previousBundleResult = getPreviousResult(entryPoint.name);
    bundleResults.set(entryPoint.name, {
      esmModuleIds: esmBundle?.moduleIds ?? previousBundleResult?.esmModuleIds ?? new Set(),
      dtsModuleIds: dtsBundle?.moduleIds ?? previousBundleResult?.dtsModuleIds ?? new Set(),
      esmOutputFiles: esmBundle?.outputFiles ?? previousBundleResult?.esmOutputFiles ?? new Set(),
      dtsOutputFiles: dtsBundle?.outputFiles ?? previousBundleResult?.dtsOutputFiles ?? new Set(),
      hasTslibImport: esmBundle?.hasTslibImport ?? previousBundleResult?.hasTslibImport ?? false,
    });
  }

  return {
    filesToEmit: [...esmOutput.filesToEmit, ...dtsOutput.filesToEmit],
    bundleResults,
    warnings: [...esmOutput.warnings, ...dtsOutput.warnings],
  };
}

/**
 * Resolves the compiled in-memory entry file path for a TypeScript entry point.
 */
function resolveEntryInputPath(entryFilePath: string, dtsMode: boolean): string {
  return dtsMode
    ? entryFilePath.replace(/\.(m?ts)$/, '.d.$1')
    : entryFilePath.replace(/\.(m?)ts$/, '.$1js');
}

/**
 * Generates the Rolldown input mapping object from the specified entry points.
 *
 * @param entryPoints The entry points to include in the bundle input map.
 * @param dtsMode Whether the input map is for declaration files (.d.ts) rather than ESM files (.js).
 * @returns A record mapping bundle names to virtual POSIX entry file paths.
 */
function resolveEntryInputMap(
  entryPoints: readonly NormalizedEntryPoint[],
  dtsMode: boolean,
): Record<string, string> {
  const input: Record<string, string> = {};
  for (const { bundleName, entryFilePath } of entryPoints) {
    input[bundleName] = resolveEntryInputPath(entryFilePath, dtsMode);
  }

  return input;
}

/**
 * Creates a Rolldown plugin that resolves and loads modules from an in-memory file map.
 *
 * @param files Map of virtual POSIX file paths to their content.
 * @param extensions Candidate extensions to probe when resolving extensionless module specifiers.
 * @param includeMap Whether source map files should also be loaded from the memory map.
 * @returns A Rolldown plugin instance.
 */
function createMemoryFileLoaderPlugin(
  files: ReadonlyMap<string, string>,
  extensions: readonly string[],
  includeMap: boolean,
): Plugin {
  const isDts = extensions === DTS_EXTENSIONS;

  return {
    name: 'memory-file-loader',
    resolveId: {
      order: 'pre',
      handler(id, importer) {
        if (id[0] === '\0') {
          return undefined;
        }

        if (!importer) {
          return files.has(id) ? { id, external: false } : undefined;
        }

        if (id[0] !== '.' && !path.isAbsolute(id)) {
          return { id, external: true };
        }

        const resolved = id[0] === '.' ? path.posix.join(path.posix.dirname(importer), id) : id;
        const normalizedResolved = resolved.replace(/\/+$/, '');

        if (files.has(normalizedResolved)) {
          return { id: normalizedResolved, external: false };
        }

        const base = normalizedResolved.replace(/\.m?js$/, '');
        if (isDts && normalizedResolved.endsWith('.mjs') && files.has(`${base}.d.mts`)) {
          return { id: `${base}.d.mts`, external: false };
        }

        for (const ext of extensions) {
          const candidate = base + ext;
          if (files.has(candidate)) {
            return { id: candidate, external: false };
          }
        }

        return undefined;
      },
    },
    load(id) {
      const code = files.get(id);
      if (code === undefined) {
        return null;
      }

      return {
        code,
        map: includeMap ? files.get(`${id}.map`) : undefined,
      };
    },
  };
}

/**
 * Processes Rolldown output assets and chunks, extracting emitted files and computing
 * the transitive sets of module IDs, output file paths, and tslib imports belonging to
 * each entry point bundle.
 *
 * @param output The array of output chunks and assets from Rolldown.
 * @param dir The destination POSIX output directory prefix.
 * @returns The processed multi-bundle output.
 */
function processRolldownOutput(
  output: RolldownOutput['output'],
  dir: string,
): Omit<MultiBundleOutput, 'warnings'> {
  const filesToEmit: MemoryOutputFile[] = [];
  const bundles = new Map<string, EntryBundleOutput>();
  const chunksByFileName = new Map<string, OutputChunk>();
  const outputFileNames = new Set<string>();
  const entryChunks: OutputChunk[] = [];

  for (const item of output) {
    outputFileNames.add(item.fileName);
    filesToEmit.push(
      createMemoryOutputFile(
        path.posix.join(dir, item.fileName),
        item.type === 'chunk' ? item.code : item.source,
      ),
    );

    if (item.type === 'chunk') {
      chunksByFileName.set(item.fileName, item);
      if (item.isEntry) {
        entryChunks.push(item);
      }
    }
  }

  for (const entryChunk of entryChunks) {
    const moduleIds = new Set<string>();
    const outputFiles = new Set<string>();
    let hasTslibImport = false;

    const visited = new Set<OutputChunk>([entryChunk]);
    for (const chunk of visited) {
      outputFiles.add(path.posix.join(dir, chunk.fileName));
      const mapFileName = `${chunk.fileName}.map`;
      if (outputFileNames.has(mapFileName)) {
        outputFiles.add(path.posix.join(dir, mapFileName));
      }

      for (const modId of chunk.moduleIds) {
        if (modId[0] !== '\0') {
          moduleIds.add(toPosixPath(modId));
        }
      }

      for (const depFile of [...chunk.imports, ...chunk.dynamicImports]) {
        if (depFile === 'tslib') {
          hasTslibImport = true;
        }

        const depChunk = chunksByFileName.get(depFile);
        if (depChunk) {
          visited.add(depChunk);
        }
      }
    }

    bundles.set(entryChunk.name, { moduleIds, outputFiles, hasTslibImport });
  }

  return { filesToEmit, bundles };
}

/**
 * Set of Rolldown warning codes that should be ignored.
 */
const IGNORED_ROLLDOWN_WARNING_CODES: ReadonlySet<string> = new Set([
  'EMPTY_BUNDLE',
  'UNUSED_EXTERNAL_IMPORT',
  'THIS_IS_UNDEFINED',
]);

/**
 * Executes a Rolldown bundle build across all provided entry inputs.
 *
 * @param input Map of bundle names to virtual POSIX entry file paths.
 * @param plugins Rolldown plugins to use during bundling.
 * @param extension Output file extension ('mjs' or 'd.ts').
 * @param options The normalized library options with POSIX paths.
 * @returns A promise resolving to the multi-bundle output.
 */
async function executeMultiBundle(
  input: Record<string, string>,
  plugins: RolldownPluginOption[],
  extension: 'mjs' | 'd.ts',
  options: NormalizedLibraryOptions,
): Promise<MultiBundleOutput> {
  const { workspaceRoot, preserveSymlinks, declarationMap, outputPath } = options;
  const isDts = extension === 'd.ts';
  const dir = isDts ? TYPES_OUTPUT_DIR : FESM_OUTPUT_DIR;
  // FESM (.mjs) sourcemaps are always enabled.
  const sourcemap = isDts ? !!declarationMap : true;

  const warnings: string[] = [];
  const { rolldown } = await loadRolldown();
  const bundle = await rolldown({
    context: 'this',
    input,
    cwd: workspaceRoot,
    tsconfig: false,
    plugins,
    treeshake: isDts,
    resolve: { symlinks: !preserveSymlinks },
    checks: { circularDependency: false, bundlerTimings: false },
    onLog(level, log) {
      // Ignore specified warning codes
      if (level === 'warn') {
        if (log.code && IGNORED_ROLLDOWN_WARNING_CODES.has(log.code)) {
          return;
        }

        warnings.push(log.message);
      }
    },
    experimental: {
      attachDebugInfo: 'none',
    },
  });

  try {
    const { output } = await bundle.generate({
      format: 'es',
      dir: path.posix.join(outputPath, dir),
      entryFileNames: `[name].${extension}`,
      chunkFileNames: `[name]-[hash].${extension}`,
      sourcemap,
      hoistTransitiveImports: false,
      comments: { jsdoc: isDts, legal: true, annotation: !isDts },
    });

    return {
      ...processRolldownOutput(output, dir),
      warnings,
    };
  } finally {
    await bundle.close();
  }
}

/**
 * Bundles JavaScript ESM output files for all provided entry points.
 *
 * @param entryPoints The entry points to bundle.
 * @param esmFiles Map of virtual POSIX ESM output file paths to contents.
 * @param options The normalized library options with POSIX paths.
 * @returns A promise resolving to the multi-bundle output.
 */
async function bundleAllEsm(
  entryPoints: readonly NormalizedEntryPoint[],
  esmFiles: ReadonlyMap<string, string>,
  options: NormalizedLibraryOptions,
): Promise<MultiBundleOutput> {
  if (entryPoints.length === 0) {
    return {
      filesToEmit: [],
      bundles: new Map(),
      warnings: [],
    };
  }

  return executeMultiBundle(
    resolveEntryInputMap(entryPoints, false),
    [createMemoryFileLoaderPlugin(esmFiles, ESM_EXTENSIONS, true)],
    'mjs',
    options,
  );
}

/**
 * Bundles TypeScript declaration (.d.ts) output files for all provided entry points.
 *
 * @param entryPoints The entry points to bundle.
 * @param dtsFiles Map of virtual POSIX declaration output file paths to contents.
 * @param options The normalized library options with POSIX paths.
 * @returns A promise resolving to the multi-bundle output.
 */
async function bundleAllDts(
  entryPoints: readonly NormalizedEntryPoint[],
  dtsFiles: ReadonlyMap<string, string>,
  options: NormalizedLibraryOptions,
): Promise<MultiBundleOutput> {
  if (entryPoints.length === 0) {
    return {
      filesToEmit: [],
      bundles: new Map(),
      warnings: [],
    };
  }

  const { createFakeJsPlugin } = await loadRolldownPluginDts();

  const dtsSourcemap = !!options.declarationMap;
  // Directly instantiate `createFakeJsPlugin` instead of calling `dts({ dtsInput: true, ... })`
  // to avoid `createDtsResolvePlugin` unconditionally instantiating a native `oxc-resolver`
  // (`ResolverFactory`) on every build. All `.d.ts` files are already emitted in-memory by the
  // Angular/TypeScript compilation and resolved via `createMemoryFileLoaderPlugin`.
  const fakeJsPlugin = createFakeJsPlugin({
    sourcemap: dtsSourcemap,
    cjsDefault: false,
    sideEffects: false,
  });

  return executeMultiBundle(
    resolveEntryInputMap(entryPoints, true),
    [createMemoryFileLoaderPlugin(dtsFiles, DTS_EXTENSIONS, dtsSourcemap), fakeJsPlugin],
    'd.ts',
    options,
  );
}
